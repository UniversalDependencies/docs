#!/usr/bin/env python3
"""Writes _data/languages.yaml: the languages known to UD, with their code, family,
genus, scripts and flag, so that scripts and Jekyll templates can use them
without parsing HTML.

The data is taken from docs-automation/codes_and_flags.yaml (the same file from which the
homepage and the table of languages are generated), downloaded from GitHub. Like there,
the family "IE" is written out as "Indo-European" and a language without genus gets its
family as genus. Re-run this script when languages were added there, then commit the result.

Usage (from the docs repository root):  python3 infrastructure/make_languages_yaml.py

    - name: Afrikaans
      code: af
      family: Indo-European
      genus: Germanic
      scripts: [Latn]
      flag: ZA
"""
import re
import sys
import urllib.request

SOURCE = 'https://raw.githubusercontent.com/UniversalDependencies/docs-automation/master/codes_and_flags.yaml'
OUTPUT = '_data/languages.yaml'


def unquote(s):
    return s[1:-1] if len(s) > 1 and s[0] == s[-1] and s[0] in '\'"' else s


def read_source():
    """The source is a flat YAML mapping: a language name, then indented 'key: value' lines."""
    languages, current = {}, None
    for line in urllib.request.urlopen(SOURCE).read().decode('utf-8').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if not line.startswith(' '):
            current = languages.setdefault(unquote(line.rstrip(':').strip()), {})
        else:
            key, _, value = line.strip().partition(':')
            current[key] = value.strip()
    return languages


def yaml_string(s):
    """Plain scalar when that is safe, otherwise a double-quoted one."""
    if re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9 .\'()/+-]*', s) and s.lower() not in ('yes', 'no', 'true', 'false', 'null'):
        return s
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    languages = read_source()
    if not languages:
        sys.exit('No languages found in %s' % SOURCE)
    with open(OUTPUT, 'w', encoding='utf-8') as out:
        out.write('# Languages known to UD. Generated by infrastructure/make_languages_yaml.py\n')
        out.write('# from docs-automation/codes_and_flags.yaml. Do not edit by hand.\n')
        for name in sorted(languages):
            info = languages[name]
            family = 'Indo-European' if unquote(info['family']) == 'IE' else unquote(info['family'])
            genus = unquote(info.get('genus', '')) or family
            scripts = info.get('scripts', '[]').strip('[]').replace(' ', '')
            out.write('- name: %s\n  code: %s\n  family: %s\n  genus: %s\n' %
                      (yaml_string(name), yaml_string(unquote(info['lcode'])), yaml_string(family), yaml_string(genus)))
            out.write('  scripts: [%s]\n' % scripts.replace(',', ', '))
            if info.get('flag'):
                out.write('  flag: %s\n' % yaml_string(unquote(info['flag'])))
    print('%d languages written to %s' % (len(languages), OUTPUT), file=sys.stderr)


if __name__ == '__main__':
    main()
